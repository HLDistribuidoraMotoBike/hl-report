SELECT

    TO_VARCHAR(ASDP."U_HL_DT_FAT", 'DD/MM/YYYY') AS "Data",
    COUNT(*) AS "Total Notas Nao Expedidas"

FROM "SBO_HLMOTOBIKE_PRD"."@HL_ASDP" AS ASDP
LEFT JOIN "SBO_HLMOTOBIKE_PRD"."ORDR" ON ORDR."DocEntry" = ASDP."Code"
LEFT JOIN "SBO_HLMOTOBIKE_PRD"."OSLP" ON OSLP."SlpCode" = ORDR."SlpCode"

WHERE ASDP."U_HL_ST_STATUS" = '05'
  AND OSLP."Memo" = 'ECOMMERCE'
  AND ASDP."U_HL_DT_FAT" <> CURRENT_DATE

GROUP BY ASDP."U_HL_DT_FAT"
ORDER BY ASDP."U_HL_DT_FAT";
