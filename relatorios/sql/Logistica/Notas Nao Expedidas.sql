SELECT

    ASDP."U_HL_ST_NF",
    ORDR."NumAtCard",
    OSLP."SlpName",

    TO_VARCHAR(ASDP."U_HL_DT_FAT", 'DD/MM/YYYY')
    || ' ' ||
    SUBSTRING(LPAD(CAST(ASDP."U_HL_TM_FAT" AS VARCHAR), 4, '0'), 1, 2)
    || ':' ||
    SUBSTRING(LPAD(CAST(ASDP."U_HL_TM_FAT" AS VARCHAR), 4, '0'), 3, 2)
    AS "DataHoraFaturamento"

FROM "SBO_HLMOTOBIKE_PRD"."@HL_ASDP" AS ASDP
LEFT JOIN "SBO_HLMOTOBIKE_PRD"."ORDR" ON ORDR."DocEntry" = ASDP."Code"
LEFT JOIN "SBO_HLMOTOBIKE_PRD"."OSLP" ON OSLP."SlpCode" = ORDR."SlpCode"

WHERE ASDP."U_HL_ST_STATUS" = '05'
  AND OSLP."Memo" = 'ECOMMERCE'
  AND ASDP."U_HL_DT_FAT" <> CURRENT_DATE

ORDER BY
    ASDP."U_HL_DT_FAT" ,
    ASDP."U_HL_TM_FAT" ;
