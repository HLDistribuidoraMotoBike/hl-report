SELECT
    T0."Code",
    T0."U_HL_DT_INICIO", 
    T0."U_HL_DT_FIM",    
    T1."U_HL_DS_ITEMCODE",
    T2."ItemName",
    T2."SWW",
    T2."U_HL_ID_FAMILIA",
    T1."U_HL_NM_DESCONTO"

FROM SBO_HLMOTOBIKE_PRD."@HL_ACDP" AS T0 
LEFT JOIN SBO_HLMOTOBIKE_PRD."@HL_ADDP" AS T1 ON T1."Code" = T0."Code"
LEFT JOIN SBO_HLMOTOBIKE_PRD.OITM AS T2 ON T2."ItemCode" = T1."U_HL_DS_ITEMCODE"

WHERE 

    CURRENT_DATE BETWEEN T0."U_HL_DT_INICIO" AND T0."U_HL_DT_FIM"